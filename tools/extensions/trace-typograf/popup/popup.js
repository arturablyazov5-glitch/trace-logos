'use strict';

const btn = document.getElementById('apply-btn');
const statusEl = document.getElementById('status');

function setStatus(text, kind) {
  statusEl.textContent = text;
  statusEl.className = 'status' + (kind ? ` ${kind}` : '');
}

const REASON_TEXT = {
  'no-target': 'Не нашли текстовое поле — кликните в него на странице и попробуйте снова.',
  'not-editable': 'Не нашли текстовое поле — выделите слой с текстом и попробуйте снова.',
  'empty': 'Поле пустое.',
  'no-change': 'Типограф уже расставлен',
  'nobreak-failed': 'Нашли, где нужен неразрывный пробел, но не смогли нажать «Прерывание». Кликните в текст, чтобы он был в режиме редактирования, и попробуйте снова.',
  'no-text-rows': 'В выбранном слое не нашли текстовых слоёв. Выберите слой с текстом или контейнер, внутри которого он есть.',
  'enter-failed': 'Нашли текст, но не смогли открыть его в редактировании. Перезагрузите страницу редактора и попробуйте снова.',
  'error': 'Ошибка при правке текста.',
};

btn.addEventListener('click', async () => {
  btn.disabled = true;
  setStatus('Запускаю на странице…');

  let tab;
  try {
    [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
  } catch (err) {
    setStatus('Не удалось получить активную вкладку.', 'err');
    btn.disabled = false;
    return;
  }

  if (!tab || !tab.id) {
    setStatus('Не удалось получить активную вкладку.', 'err');
    btn.disabled = false;
    return;
  }

  // Подстраховка на случай зависания в контент-скрипте (там своя защита —
  // жёсткие таймауты/лимиты на все ожидания и циклы, — но лучше не
  // держать кнопку залипшей на "Применяю…" вечно, если где-то в будущем
  // найдётся ещё не учтённый хэнг). Обход большого контейнера с
  // повторяющимися виджетами может занять реально долго (секунды на
  // каждый найденный текст) — 5 минут с запасом: контейнер вроде
  // work-many-item на реальной странице даёт 30+ текстовых слоёв, а это
  // уже за пределами прежних 60с, и попап рвал живой прогон по таймауту.
  // ПОПАП ЗАКРЫВАЕТСЯ СРАЗУ ПОСЛЕ СТАРТА (2026-08-21) — это не UX-каприз,
  // а условие работоспособности. Попап — отдельное окно ОС: пока он
  // открыт, document.hasFocus() на странице редактора false, выделение
  // рисуется серым, а Taptop не поднимает панель «Прерывание» на
  // несфокусированном Draft.js — цикл неразрывных пробелов уходит в
  // failed. Отобрать фокус окна обратно из content script нельзя.
  // Поэтому прогресс и итог показывает панель НА СТРАНИЦЕ
  // (src/ui/progressOverlay.js), а попапу остаётся только отдать команду.
  //
  // Закрытие отложено на CLOSE_DELAY_MS: если content script'а во вкладке
  // нет вовсе (не Taptop/Tilda), chrome.runtime.lastError приходит почти
  // мгновенно — этот случай успевает отмениться и показать ошибку прямо
  // здесь, потому что показать её больше негде: панели на странице без
  // content script'а тоже не будет.
  const CLOSE_DELAY_MS = 400;
  let closeTimer = setTimeout(() => window.close(), CLOSE_DELAY_MS);

  chrome.tabs.sendMessage(tab.id, { type: 'APPLY_TYPOGRAF' }, (response) => {
    if (chrome.runtime.lastError) {
      // Нет живого слушателя во вкладке — либо страница не Taptop/Tilda,
      // либо код там устарел (расширение обновили, пока вкладка была
      // открыта — Chrome не переинжектит content script в уже открытую
      // вкладку сам). Отличить эти два случая с одной стороны попапа
      // нечем, а автоматически чинить второй случай раньше пытался целый
      // механизм пингов/штампов/впрыскивания — он сам стал источником
      // непредсказуемых сбоев (2026-08-22). Один явный совет вместо него:
      // обновить страницу это чинит оба случая разом.
      clearTimeout(closeTimer);
      btn.disabled = false;
      setStatus('Не получилось — перезагрузите страницу редактора (Cmd+R) и попробуйте снова.', 'err');
      return;
    }

    // Сюда попадаем, только если работа закончилась быстрее CLOSE_DELAY_MS
    // (редкий случай — например, «нечего менять»). Обычно попап к этому
    // моменту уже закрыт, и колбэк не выполняется вовсе: итог показывает
    // панель на странице.
    clearTimeout(closeTimer);
    btn.disabled = false;

    if (!response) {
      setStatus(REASON_TEXT['no-target'], 'err');
      return;
    }

    if (!response.ok) {
      setStatus(REASON_TEXT[response.reason] || 'Не получилось.', 'err');
      return;
    }

    // Диагностическая строка под ответом. Показывается всегда, когда
    // расширение реально проходило по слоям: без неё "уже без замечаний"
    // и "ничего не смог" выглядят в окошке одинаково, и понять, что
    // произошло, можно только через DevTools — которых у пользователя в
    // момент работы обычно не открыто.
    const s = response.stats;
    let detail = '';
    if (s) {
      if (s.focused) {
        detail = 'Правил сфокусированное поле.';
      } else {
        // Прозой, а не цифрами в столбик — но visited/entered/count
        // считают СЛОИ, а already/failed считают неразрывные пробелы
        // ВНУТРИ слоёв (applyTypografToTaptopSelection.js суммирует их
        // через += по каждому слою) — already/failed легко превышает
        // число слоёв. Склеив их в одну фразу без единиц ("Слоёв: 5 ...
        // уже верно: 9"), получаешь на вид 9 из 5 — бессмыслицу. Поэтому
        // разные единицы — разные предложения, каждое с существительным.
        detail = `Проверено слоёв с текстом: ${s.visited}.`;
        if (s.entered < s.visited) detail += ` Открыто для правки: ${s.entered}.`;
        if (s.count) detail += ` Изменено слоёв: ${s.count}.`;
        if (s.already) detail += ` Неразрывных пробелов уже было на месте: ${s.already}.`;
        if (s.failed) detail += ` Не удалось расставить пробелов: ${s.failed}.`;
      }
    }

    if (response.changed) {
      setStatus('Готово — типографика расставлена. ' + detail, 'ok');
    } else {
      setStatus((REASON_TEXT[response.reason] || 'Менять нечего.') + (detail ? ' ' + detail : ''), 'ok');
    }
  });
});
