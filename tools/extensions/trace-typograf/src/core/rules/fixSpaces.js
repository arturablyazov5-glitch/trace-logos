// Схлопывает двойные пробелы, убирает пробел перед знаком препинания,
// невидимые unicode-пробелы, табы и хвостовые/ведущие пробелы по строкам.
function fixSpaces(text) {
  return text
    .replace(/[​‎‏﻿]/g, '')
    .replace(/\t/g, ' ')
    .replace(/[  ]{2,}/g, ' ')
    .replace(/[  ]+([,.:;!?…\]])/g, '$1')
    .replace(/\[[  ]+/g, '[')
    .replace(/[ \t ]+$/gm, '')
    .replace(/^[ \t ]+/, '');
}
