// Taptop хранит "неразрывность" не как символ НБСП (U+00A0) внутри текста,
// а как собственный виджет "Прерывание" (в панели справа при редактировании
// текста) — при сохранении он сериализует такой участок в
// <span style="white-space:pre">, а не в текст с литеральным НБСП.
//
// Обнаружено вживую 2026-08-10: если вставить литеральный НБСП через
// execCommand('insertText', …) в их Draft.js-редактор, символ выглядит
// на месте, пока курсор в поле, но при выходе из редактирования Taptop
// пересобирает содержимое из своей внутренней модели — и перенос слова
// реально ломается (не просто визуальный нюанс, а settled-баг: слово
// после "пробела" может перенестись на новую строку как обычно).
//
// Их собственный виджет "Прерывание" мы отсюда не дёргаем (это отдельная,
// более сложная фича — нужно найти, как программно включать именно его,
// не строку с НБСП). Пока — просто не вставляем НБСП на этой платформе:
// обычный пробел не защищает от переноса, но хотя бы не роняет остальную
// типографику (тире/кавычки/многоточие продолжают сохраняться нормально).
function stripNbspForTaptop(text) {
  return text.split(NBSP).join(' ');
}
