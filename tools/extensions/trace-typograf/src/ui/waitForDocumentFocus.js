// Ждёт, пока документ страницы снова станет активным окном.
//
// Команда приходит из попапа расширения, а он — отдельное окно ОС и
// держит фокус, пока открыт. Попап теперь закрывается сразу после
// отправки команды (popup.js), но закрытие асинхронно: если начать
// работу в тот же миг, первые слои обработаются в НЕсфокусированном
// документе — ровно тот случай, ради которого всё это и переделано
// (серое выделение, панель «Прерывание» не поднимается). Поэтому просто
// ждём document.hasFocus().
//
// Таймаут не фатален: возвращаем false и всё равно пробуем работать —
// хуже, чем было, от этого не станет, а вкладка могла быть неактивной
// по совсем другой причине (пользователь ушёл в другое окно).
function waitForDocumentFocus(timeout) {
  if (document.hasFocus()) return Promise.resolve(true);
  const deadline = Date.now() + (timeout || 2000);
  return new Promise((resolve) => {
    (function check() {
      if (document.hasFocus()) return resolve(true);
      if (Date.now() > deadline) return resolve(false);
      setTimeout(check, 60);
    })();
  });
}
