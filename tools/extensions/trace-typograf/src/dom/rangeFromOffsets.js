// Строит Range на реальных Text-нодах по офсетам в плоской строке
// root.textContent, используя карту от textNodeOffsetMap.js.
//
// РОВНО НА ГРАНИЦЕ двух соседних текстовых узлов offset одновременно
// валиден как [конец предыдущего узла] И как [начало следующего узла] —
// DOM-позиция та же самая, но Range хранит конкретный (node, offset), и
// эти два варианта — РАЗНЫЕ пары. Раньше выбирался первый подходящий по
// `<=`, то есть КОНЕЦ предыдущего узла. Это не совпадает с тем, как
// браузер сам разрешает такую границу при обычном пользовательском
// выделении (мышью/клавиатурой) — оно естественно попадает на НАЧАЛО
// следующего узла.
//
// Разница не заметна, пока весь текст — один плоский узел. Но как только
// в поле уже есть несколько узлов (Taptop оборачивает часть текста в
// <span> при клике по "Прерывание" — см. applyTaptopNoBreakRuns.js), а мы
// в том же прогоне выделяем СЛЕДУЮЩИЙ фрагмент, чья граница ровно
// упирается в этот новый узел, — [конец предыдущего] и [начало
// следующего] перестают быть эквивалентны для ИХ Draft.js-редактора: он
// разбирает нативное выделение через собственные data-атрибуты на каждом
// узле (offset-key), и "конец предыдущего листа" резолвится в другой
// участок их внутренней модели, чем "начало следующего". Обнаружено
// вживую 2026-08-21: автоматическое выделение "и что с ним" (граница
// ровно там, где заканчивается wrap от предыдущего клика) стирало текст
// при клике по их кнопке, хотя ТО ЖЕ САМОЕ выделение мышью руками — цело.
//
// Фикс: на точной границе всегда предпочитать НАЧАЛО следующего узла
// (кроме самого последнего узла в карте, где следующего просто нет) —
// та же конвенция, которую использует обычное выделение в браузере.
// Середины узлов это не касается вообще — правится только неоднозначный
// случай offset === entry.end.
function locateOffset(root, map, offset) {
  for (let i = 0; i < map.length; i++) {
    const entry = map[i];
    if (offset < entry.end) {
      return { node: entry.node, offset: Math.max(0, offset - entry.start) };
    }
    if (offset === entry.end) {
      const next = map[i + 1];
      if (next) return { node: next.node, offset: 0 };
      return { node: entry.node, offset: entry.end - entry.start };
    }
  }
  // Пустой контейнер или офсет за пределами карты (не должно случаться при
  // корректных hunks, но лучше воткнуться в конец корня, чем упасть).
  return { node: root, offset: root.childNodes.length };
}

function rangeFromOffsets(root, map, start, end) {
  const from = locateOffset(root, map, start);
  const to = locateOffset(root, map, end);
  const range = document.createRange();
  range.setStart(from.node, from.offset);
  range.setEnd(to.node, to.offset);
  return range;
}
