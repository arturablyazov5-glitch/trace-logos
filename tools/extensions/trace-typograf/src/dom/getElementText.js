// Текущий текст редактируемого корня как плоская строка.
//
// Для contenteditable намеренно textContent, а не innerText: innerText
// вставляет свои "\n" на границах блочных элементов, которые не
// соответствуют настоящим Text-нодам — тогда офсеты диффа не совпали бы с
// офсетами, которые строит textNodeOffsetMap.js для реального применения
// правки. Плата за это — типографика не видит разрыв абзаца между соседними
// <div>/<p> (они просто склеятся), для v1 приемлемо. <br> отдельно
// учитывать не нужно — applyTypografToElement.js заранее заменяет его на
// обычный пробел через normalizeBrToSpace.js, до того как этот текст
// вообще читается (см. его комментарий про историю с потерей текста).
function getElementText(el) {
  if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') return el.value;
  return el.textContent;
}
