// ─────────────────────────────────────────────────────────────────────────────
// Правила типографики — чистые строковые функции, ничего не знают о Figma.
// JS \b считает границей слова только [A-Za-z0-9_] — кириллица в эту категорию
// не входит, поэтому \b между двумя русскими буквами НЕ срабатывает. Все правила
// ниже вместо \b используют явный класс символов слова и захват символа-соседа.
// ─────────────────────────────────────────────────────────────────────────────

const NBSP = ' ';
const EM_DASH = '—';
const EN_DASH = '–';
const ELLIPSIS = '…';
// Неразрывный дефис (U+2011) — для тире без пробелов вокруг, как в числовом
// диапазоне "2015–2020". Пробовали невидимый WORD JOINER (U+2060) по обе
// стороны от обычного тире — не сработало: движок вёрстки Figma всё равно
// переносит строку прямо после тире, зная его как точку возможного разрыва,
// и не учитывает соседний невидимый символ. U+2011 надёжнее, потому что
// «не переноси здесь» — встроенное свойство САМОГО символа, а не подсказка
// по соседству, которую движок волен проигнорировать. Компромисс: в
// большинстве шрифтов он рисуется как обычный дефис (короче типографского
// тире), а не как «короткое тире» (en dash) — в диапазоне цифр это
// приемлемо, разница почти незаметна на глаз.
const NON_BREAKING_HYPHEN = '\u2011';

const LETTER_CLASS = 'A-Za-zА-ЯЁа-яё';
const NOT_LETTER = `[^${LETTER_CLASS}]`;
const LETTER_RE = new RegExp(`[${LETTER_CLASS}]`);
const WORD_START_RE = new RegExp(`[${LETTER_CLASS}0-9]`);

// Предлоги и союзы — неразрывный пробел ставится ПОСЛЕ них (слово не должно
