function fixEllipsis(text) {
  return text.replace(/\.{3,}/g, ELLIPSIS);
}

function fixSpaces(text) {
  return text
    // Невидимые управляющие символы из копипаста (WhatsApp, Notion,
    // Google Docs и т. п. проставляют их для управления направлением
    // текста) — LRM/RLM (U+200E/U+200F), BOM/zero-width no-break space
    // (U+FEFF), zero-width space (U+200B). Сами по себе незаметны, но
    // вставшие между двумя обычными пробелами ("28 <LRM> = 448") рвут их
    // на два однопробельных участка — схлопывание "двух и более пробелов
    // подряд" ниже это не ловит, пока сам невидимый символ не убран первым
    // шагом. ZWJ (U+200D) и вариационные селекторы (FE0F/FE0E) сюда
    // намеренно НЕ входят — это настоящая часть emoji-последовательностей
    // (см. fixEmojiSpacing выше), удалять их нельзя.
    .replace(/[\u200B\u200E\u200F\uFEFF]/g, '')
    .replace(/\t/g, ' ')
    // Класс включает и уже неразрывный пробел (U+00A0), не только обычный:
    // копипаст из Notion/Google Docs/Figma-автозамены иногда оставляет NBSP
    // ВНУТРИ серии из нескольких пробелов подряд ("гонорар    с одного"),
    // и класс из одного лишь " " такую серию не находит целиком — сначала
    // схлопывались бы только обычные пробелы по обе стороны от NBSP, а сам
    // NBSP оставался бы посередине как отдельный "пробел" шириной в один
    // символ. Итог тот же, что и раньше — одиночный ОБЫЧНЫЙ пробел; если
    // грамматика требует здесь неразрывный (предлог/частица), его поставит
    // отдельный проход fixShortWords/fixNumbers, идущий позже в typografize.
    .replace(/[  ]{2,}/g, ' ')
    .replace(/[  ]+([,.:;!?…\])])/g, '$1')
    // Пробел сразу после открывающей квадратной ИЛИ круглой скобки — тот же
    // принцип, что и для закрывающей выше: "[ доход]" → "[доход]",
    // "( текст )" → "(текст)". Плейсхолдеры вида "[желаемый доход]" часто
    // вставляют из шаблона с лишним пробелом внутри скобки; сама скобка при
    // этом остаётся, лишний только пробел сразу после неё. Круглые — тот же
    // артефакт, обычно из вставки "(  примечание)" при копипасте. Оба вида
    // пробела (обычный и уже неразрывный), как и в правиле для закрывающей.
    .replace(/[[(][  ]+/g, (m) => m[0])
    .replace(/[ \t ]+$/gm, '')
    // Пробел в самом начале ВСЕГО текста — не по каждой строке (иначе снёс
    // бы намеренный отступ вложенного пункта списка, который
    // stripListMarkers специально сохраняет). Такой пробел иногда остаётся
    // утёкшим артефактом — например, от бага в fixEmojiSpacing (см. её
    // комментарий выше): раньше эмодзи в самом начале текста мог получить
    // перед собой пробел, которого там не должно было быть. Тот баг починен,
    // но уже вставленный им пробел сам себя не уберёт — для этого нужен
    // именно этот шаг.
    .replace(/^[ \t\u00a0]+/, '');
}

// Эмодзи, прилипший к тексту без пробела ("текст🥵🥵🥵") — обычный результат
// копипаста из мессенджера или соцсети, где пробел перед эмодзи не ставят.
// \p{Extended_Pictographic} — официальный юникодовый набор emoji-подобных
// кодпоинтов, шире просто "эмодзи" (включает символы-кандидаты), но для
// разделения текст/эмодзи это ровно то, что нужно. Флаги ("🇷🇺") в него НЕ
// входят — это пара кодпоинтов из отдельного свойства Regional_Indicator,
// поэтому целевая группа матчит оба свойства через |. Неразрывный пробел
// (NBSP, см. fixEmojiSpacing) ставится только перед ПЕРВЫМ эмодзи серии:
// lookbehind требует, чтобы ПЕРЕД эмодзи стоял реальный символ, который не
// пробел (\s матчит и обычный, и неразрывный) и не сам emoji-компонент
// (вариационный селектор, ZWJ, тон кожи, Regional_Indicator) — иначе внутри
// одной серии ("🥵🥵🥵", флага "🇷🇺" из двух индикаторов или
// ZWJ-последовательности вроде 👨‍👩‍👧) пробел влез бы и между ними же.
// ПОЗИТИВНЫЙ lookbehind с отрицанием класса внутри — не негативный: у
// негативного (?<![...]) "символа из класса нет прямо перед" ложно
// засчитывается и тогда, когда перед текущей позицией вообще НЕТ никакого
// символа (начало строки) — /(?<!x)y/.test('y') === true. Из-за этого
// "©️ Все права защищены" (copyright — тоже Extended_Pictographic) в самом
// начале текста получало пробел ПЕРЕД собой, хотя разделять там нечего.
// Позитивный (?<=[^...]) требует реального предыдущего символа и сам не
// матчится, если позиция — начало строки.
const EMOJI_RELATED = '\\p{Extended_Pictographic}\\p{Regional_Indicator}\\u{FE0F}\\u{FE0E}\\u{200D}\\u{1F3FB}-\\u{1F3FF}\\u{20E3}';
const EMOJI_GAP_RE = new RegExp(`(?<=[^\\s${EMOJI_RELATED}])(\\p{Extended_Pictographic}|\\p{Regional_Indicator})`, 'gu');

function fixEmojiSpacing(text) {
  // Неразрывный, не обычный: иначе при переносе строки эмодзи может оторваться
  // от последнего слова и остаться одно в начале следующей строки.
  return text.replace(EMOJI_GAP_RE, `${NBSP}$1`);
}

// Текстовые смайлы (эмотиконы) — тот же принцип, что и для настоящих эмодзи
// выше: приклеенный к слову без пробела смайл ("субботу:)") получает перед
// собой неразрывный пробел ("субботу :)"). Глаза — только ":"/";", не "="
// и не "8": "8)" в русском тексте почти всегда номер пункта списка
// ("8) сделать это"), а не эмотикон, и это правило не должно его трогать.
// Нос — необязательный "-". Рот — ограниченный набор самых частых форм.
// Лукбехайнд "перед смайлом стоит непробельный символ" — не трогаем смайл в
// самом начале текста (там добавлять пробел спереди нечего) и не трогаем
// уже отделённый пробелом. Лукахед "дальше не буква/цифра" — не даёт
// частично совпасть на настоящем слове вроде ":Pavel" (там "P" — начало
// имени, а не рот смайла ":P").
// Компромисс: "смотри:(текст)" без пробела после двоеточия прочитается как
// приклеенный смайл ":(" — реже это и правда двоеточие перед скобкой без
// пробела (нетипично для русского текста, обычно после ":" пробел ставят),
// чаще — ровно тот случай, который просили исправить.
//
// Два исключения ниже добавлены отдельно от самого регэкспа — в колбэке
// replace, не в паттерне, потому что каждое смотрит НАРУЖУ совпадения
// (символ ПОСЛЕ него для URL, символ ПЕРЕД ним для диапазона), а не внутрь:
// 1) URL "https://…" — класс лица включает "/", и ":" перед первым "/" в
//    "://" читается как смайл ":/" (неопределённое лицо): лукбехайнд видит
//    непробельную "s" перед ":", лукахед не запрещает второй "/" (он не
//    буква и не цифра) — совпадение проходит, вставляя пробел прямо внутрь
//    протокола ("https ://brand.com"). Проверяем: если совпадение
//    заканчивается на "/" и СЛЕДУЮЩИЙ символ в строке — тоже "/", это не
//    лицо, а начало "//" из адреса — не трогаем.
// 2) "цифра:цифра" — соотношения сторон (4:3), тайминги — класс лица
//    включает цифру "3" (эмодзи "кот" ":3"), и "4:3" перед закрывающей
//    скобкой/точкой матчится тем же образом. Проверяем: если совпадение
//    заканчивается на "3" и символ ПЕРЕД совпадением — цифра, это не лицо,
//    а вторая половина числового диапазона — не трогаем. Жертвуем
//    гипотетическим смайлом сразу после цифры ("5:3" как "пять, кот") —
//    в обычном тексте такое практически не встречается, а "N:N"-нотация
//    (пропорции, время) — обычное дело.
const EMOTICON_RE = /(?<=\S)([:;]-?[)(DPp3|\\/Oo])(?![A-Za-zА-ЯЁа-яё0-9])/g;

function fixEmoticons(text) {
  return text.replace(EMOTICON_RE, (m, _face, offset, str) => {
    if (m.endsWith('/') && str[offset + m.length] === '/') return m;
    if (m.endsWith('3') && /\d/.test(str[offset - 1] || '')) return m;
    return NBSP + m;
  });
}

// Все «тире-подобные» символы между цифрами — дефис, короткое/длинное тире,
// минус, figure dash, horizontal bar. Ловим не только дефис-минус, потому что
// диапазон мог уже прийти с другим символом: пользователь напечатал сразу
// длинное тире, или это результат ПРЕДЫДУЩЕГО прогона плагина (раньше
// диапазон конвертировался в обычное «короткое тире» — оно переносится
// строкой в Figma, и без повторной нормализации так и осталось бы).
const DASH_LIKE = '\\-–—−‒―';

function fixDashes(text) {
  return text
    // числовой диапазон: 2019-2020 → неразрывный дефис, без пробелов
    .replace(new RegExp(`(\\d)\\s*[${DASH_LIKE}]\\s*(\\d)`, 'g'), `$1${NON_BREAKING_HYPHEN}$2`)
    // тире между словами: "слово - слово" → неразрывный пробел + — + пробел.
    // Неразрывный пробел ставится только ПЕРЕД тире — это не даёт тире
    // оказаться одному в начале новой строки при переносе.
    .replace(/(\S)\s+--?\s+(?=\S)/g, `$1${NBSP}${EM_DASH} `)
    // Уже готовое тире "—" между словами (набрано напрямую или вставлено не
    // этим плагином) — нормализуем пробелы вокруг него тем же способом, что
    // и при конвертации дефиса выше, независимо от того, что там было:
    // ничего ("текст—текст"), обычный пробел с одной стороны или вообще без
    // пробела с одной из сторон. Правило выше конвертирует только литеральный
    // "-"/"--" — уже стоящий символ "—" оно не трогает вообще, поэтому нужен
    // отдельный шаг. (\S) перед \s* не даёт сработать на тире-маркере
    // списка в начале строки — там перед ним только перенос строки, не
    // видимый символ. "\s" вместо "[ \t]" — по той же причине, что и у
    // +/=/÷ ниже: пробел вокруг тире мог оказаться уже неразрывным или
    // другим юникодовым пробельным символом, литеральный " "/"\t" его не
    // матчит, и правило молча не срабатывает на части пробела.
    .replace(/(\S)\s*—\s*(?=\S)/g, `$1${NBSP}${EM_DASH} `)
    // тире-маркер списка в начале строки
    .replace(/^([ \t]*)-[ ]+(?=\S)/gm, `$1${EM_DASH} `)
    // Дефис ВНУТРИ слова, без пробелов вокруг ("что-то", "по-новому", "5-й",
    // "интернет-магазин") — тоже не должен переноситься: разрыв прямо на
    // дефисе разваливает слово визуально на "что-" / "то" на разных строках.
    // Тот же приём, что для числового диапазона выше (U+2011), только
    // граница — буква/цифра с обеих сторон, а не только цифра. Идёт
    // последним: к этой строке дефис в диапазоне и в "слово - слово" уже
    // заменён на другие символы, так что здесь остаются только настоящие
    // дефисы-внутри-слова — литеральный "-", не DASH_LIKE (тире-подобные
    // символы внутри слова уже большая редкость, а не типографская ошибка,
    // трогать их не нужно).
    .replace(new RegExp(`([${LETTER_CLASS}0-9])-(?=[${LETTER_CLASS}0-9])`, 'g'), `$1${NON_BREAKING_HYPHEN}`);
}

// Кавычки-«ёлочки» вместо прямых и уже «умных» (curly). Автозамена в Figma,
// Word, Google Docs и т.п. превращает "текст" в “текст” ещё до того, как текст
// попадает к нам — “ ” уже несут направление (открывающая/закрывающая), это
// просто прямая замена символа без переключателя. Прямые `"` такого признака
// не имеют, поэтому для них — переключатель open/close, как и раньше:
// корректно для одного уровня вложенности; двойные кавычки внутри кавычек
// (редкость для названий брендов и коротких текстов логотипов) не различает.
function fixQuotes(text) {
  let out = text.replace(/[“”]/g, (m) => (m === '“' ? '«' : '»'));
  let open = true;
  out = out.replace(/"/g, () => {
    const ch = open ? '«' : '»';
    open = !open;
    return ch;
  });
  return out;
}

// Апостроф в именах и иностранных словах ("Д'Артаньян", "O'Brien") — прямой
// ' (U+0027, обычная клавиатурная кавычка) заменяется на настоящий
// типографский апостроф ’ (U+2019 — та же "правая одинарная кавычка", но с
// другим значением здесь). Матчится ТОЛЬКО между двумя буквами без пробела —
// так апостроф-внутри-слова не путается с одиночной кавычкой-цитатой: та
// почти всегда граничит с пробелом или пунктуацией хотя бы с одной стороны,
// а не стоит впритык между двумя буквами.
function fixApostrophe(text) {
  return text.replace(new RegExp(`([${LETTER_CLASS}])'([${LETTER_CLASS}])`, 'gu'), '$1’$2');
}

function fixAbbreviations(text) {
  const rules = [
    [new RegExp(`(^|${NOT_LETTER})[тТ]\\.[  ]*д\\.`, 'g'), `$1т.${NBSP}д.`],
    [new RegExp(`(^|${NOT_LETTER})[тТ]\\.[  ]*п\\.`, 'g'), `$1т.${NBSP}п.`],
    [new RegExp(`(^|${NOT_LETTER})[тТ]\\.[  ]*е\\.`, 'g'), `$1т.${NBSP}е.`],
    [new RegExp(`(^|${NOT_LETTER})[тТ]\\.[  ]*к\\.`, 'g'), `$1т.${NBSP}к.`],
    [new RegExp(`(^|${NOT_LETTER})[иИ][ ]+др\\.`, 'g'), `$1и${NBSP}др.`],
    [new RegExp(`(^|${NOT_LETTER})([Сс]м\\.)[ ]`, 'g'), `$1$2${NBSP}`],
    [new RegExp(`(^|${NOT_LETTER})([Нн]апр\\.)[ ]`, 'g'), `$1$2${NBSP}`],
    // Книжные/документные ссылки — сокращение стоит ПЕРЕД тем, к чему
    // относится (обычно номером), пробел после точки апгрейдится тем же
    // способом, что "см."/"напр." выше: только уже существующий, новый не
    // вставляется (та же логика, что и у адресных сокращений ниже).
    [new RegExp(`(^|${NOT_LETTER})([Рр]ис\\.)[ ]`, 'g'), `$1$2${NBSP}`],
    [new RegExp(`(^|${NOT_LETTER})([Тт]абл\\.)[ ]`, 'g'), `$1$2${NBSP}`],
    [new RegExp(`(^|${NOT_LETTER})([Гг]л\\.)[ ]`, 'g'), `$1$2${NBSP}`],
  ];
  let out = text;
  for (const [re, rep] of rules) out = out.replace(re, rep);
  return out;
}

// Адресные сокращения — «г. Москва», «ул. Ленина», «д. 5», «кв. 10».
// Сокращение стоит ПЕРЕД тем, к чему относится (числом или именем с большой
// буквы), поэтому неразрывный пробел — после точки, как у "т. д." выше.
const ADDRESS_PREFIX_ABBR = ['г', 'ул', 'пр-т', 'просп', 'пер', 'пос', 'д', 'кв', 'стр', 'корп', 'с'];

function fixAddressAbbreviations(text) {
  let out = text;
  const alt = ADDRESS_PREFIX_ABBR.slice().sort((a, b) => b.length - a.length).join('|');
  out = out.replace(new RegExp(`(^|${NOT_LETTER})(${alt})\\.[ ](?=\\d|[А-ЯЁ])`, 'g'), (_m, p1, abbr) => `${p1}${abbr}.${NBSP}`);
  // «область»/«район» — обратный случай: сокращение стоит ПОСЛЕ имени
  // («Московская обл.», «Ленинский р-н»), пробел перед ним приклеивается
  // к предыдущему слову.
  out = out.replace(/(\S)[ ](обл\.|р-н)/g, `$1${NBSP}$2`);
  return out;
}

// Символы валют — числа СПРАВА (100 ₽, 50 $), под русскую манеру написания
// цены, получают пробел (см. ниже). Числа СЛЕВА от символа ("$100", "$ 100")
// — западная манера — наоборот, идут БЕЗ пробела вообще, тем же принципом,
// что и №/#/%: символ здесь глухой маркер-перед-числом, а не единица
// измерения — пробел убирается, если стоял, не вставляется, если не стоял.
const CURRENCY_SIGNS = '₽|\\$|€|£';
// Те же символы, но как класс символов (без "|") — для использования внутри
// "[...]", где чередование через "|" не работает так, как в обычном regex.
const CURRENCY_CLASS = '₽\\$€£';

// Телефонные номера — сводим ЛЮБОЙ формат российского мобильного к единому
// виду "+7 (953) 837-14-29": в текст их обычно копируют с визиток, из форм
// заявок, из подписей — где стоит "+7" или "8", есть ли скобки/дефисы и
// сколько пробелов, никто не выравнивает, а разные записи одного и того же
// номера на одном макете читаются как ошибка вёрстки.
// Ищем 11 цифр подряд (код страны/выхода + 10 цифр номера), между которыми
// может стоять любое количество (в т. ч. ноль) пробелов/дефисов/скобок —
// одним этим правилом покрываются все перечисленные пользователем варианты:
// "+79538371429", "89538371429", "8 (953) 837-14-29", "+7(953)837-1429",
// "+7(953)8371-429" и т. д., независимо от того, где именно внутри номера
// стоят разделители. Первая цифра (7 или 8) в результате всегда "+7" —
// это один и тот же код страны, записанный по-разному.
// Лукбехайнд/лукахед — не давать соседней цифре или букве попасть в номер
// или обрезать его: иначе 12-значный ID мог бы случайно потерять/присвоить
// себе одну цифру, приняв первые/последние 11 за телефон.
// Вызывается ДО fixNumbers: тот группирует любую цифровую последовательность
// от 5 цифр разрядами по три — без этого номер сначала превратился бы в
// "89 538 371 429", и распознать в нём телефон было бы уже нельзя.
// Класс разделителей включает не только обычные "-"/" ", но и неразрывный
// дефис (U+2011) и неразрывный пробел (NBSP) — к моменту вызова fixPhone
// (после fixDashes в общем конвейере typografize) дефис между двумя цифрами
// ("837-14") уже мог превратиться в неразрывный тем отдельным правилом,
// иначе номер с уже гулявшим по тексту неразрывным дефисом не опознался бы.
function fixPhone(text) {
  const PHONE_RE = new RegExp(`(?<![\\d${LETTER_CLASS}])(?:\\+?7|8)(?:[ ${NBSP}\\-${NON_BREAKING_HYPHEN}()]*\\d){10}(?![\\d${LETTER_CLASS}])`, 'g');
  return text.replace(PHONE_RE, (m) => {
    const digits = m.replace(/\D/g, '').slice(-10);
    const area = digits.slice(0, 3);
    const p1 = digits.slice(3, 6);
    const p2 = digits.slice(6, 8);
    const p3 = digits.slice(8, 10);
    return `+7${NBSP}(${area})${NBSP}${p1}-${p2}-${p3}`;
  });
}

function fixNumbers(text) {
  let out = text;
  // Два ПРОТИВОПОЛОЖНЫХ режима ниже, оба обсуждались и подтверждены явно:
  // — №, # и % — пробела не должно быть ВООБЩЕ: "№ 5" → "№5", "# 5" → "#5",
  //   "50 %" → "50%". Если пробел уже стоял — убирается; если не стоял —
  //   ничего вставлять не нужно. Это глухие маркеры-перед-числом (№, #) и
  //   устойчиво слитная форма (%), не пропущенный пробел, который надо
  //   исправлять. § сюда же — структурно тот же знак-перед-числом, что №.
  // — Валюты (₽/$/€/£, включая "р."/"евро" словом), единицы измерения и
  //   "10 г./гг./в./вв." (год/годы/век/века) — наоборот, пробел ВСТАВЛЯЕТСЯ,
  //   даже если его не было вовсе ("100р." → "100 ₽", "10кг" → "10 кг"):
  //   слитное написание тут почти всегда просто пропущенный пробел, а не
  //   осознанный стиль. Единственное исключение — символ валюты ПЕРЕД
  //   числом ("$100", "$ 100", западная манера написания цены) — этот
  //   случай, наоборот, идёт в первую группу (без пробела вообще): если
  //   пробел стоял — убирается, если нет — не вставляется. См. отдельное
  //   правило ниже.
  // "\s" вместо литерального пробела " " — намеренно: между символом и
  // числом место пробела иногда уже занято НЕразрывным пробелом (например,
  // если текст набирали в редакторе с автозаменой, вставляющей NBSP перед
  // валютой) или другим юникодовым пробельным символом. Литеральный " "
  // (0x20) такое не матчит вообще, и правило удаления/вставки просто
  // молча не срабатывает — снаружи выглядит как «пробел не убрался».
  // "\s?" вместо "\s" в правилах со вставкой — та же замена работает что
  // при существующем пробеле (любом), что без него, вместо двух похожих regex.
  // "[^\S\n]" вместо "\s" везде ниже — та же причина, что у "+"/"="/"÷" выше:
  // "\s" матчит перенос строки, а перенос — граница АБЗАЦА. Число и единица
  // измерения на разных абзацах ("20\nр.") не должны склеиваться в один абзац —
  // это ломает applyTypography, который применяет правки строго по абзацам
  // старого и нового текста (см. баг с "по 9\nпараметрам", где реальный перенос
  // строки между двумя абзацами полностью пропадал).
  out = out.replace(/№[^\S\n]+(?=\d)/g, '№');
  out = out.replace(/#[^\S\n]+(?=\d)/g, '#');
  out = out.replace(/§[^\S\n]+(?=\d)/g, '§');
  out = out.replace(/(\d)[^\S\n]+%/g, '$1%');
  // "градус"/"градуса"/"градусов" после числа → символ "°", без пробела —
  // тот же принцип, что и у "%" выше: устойчиво слитная форма записи
  // температуры/углов, не пропущенный пробел. Регистронезависимо; граница
  // по классу букв защищает от "градусника"/"градусника" и т. п.
  out = out.replace(new RegExp(`(\\d)[^\\S\\n]*градус(?:а|ов)?(?![${LETTER_CLASS}])`, 'gi'), '$1°');
  // "Квадратный метр" — устойчивые текстовые варианты написания приводятся
  // к канонической форме "м²" (m с НАДСТРОЧНОЙ двойкой, U+00B2, а не обычная
  // цифра "2" рядом с "м" — это разные символы, "50м2" не то же самое, что
  // "50 м²"): "50 кв/м2" → "50 м²", "30кв.м." → "30 м²", "напишем... кв/м2"
  // (без числа рядом) → "...м²". Курируемый список конкретных написаний, не
  // общий regex "любое сокращение метра" — слишком легко словить ложное
  // совпадение.
  //
  // Две группы разной строгости:
  // — SQM_SPECIFIC — самодостаточные написания (с "кв" — устойчивым
  //   сокращением "квадратный", которое само по себе почти не встречается
  //   ни в чём другом): конвертируются ВСЕГДА, даже без числа рядом.
  // — SQM_BARE — голое "м2"/"м²" без "кв" — слишком общий паттерн сам по
  //   себе: "терем 2", "дом 2" тоже подходят под "буква м + пробел + 2",
  //   если не требовать числа СЛЕВА как якоря. Конвертируется только когда
  //   перед этим "м2" стоит цифра — то есть весь фрагмент выглядит как
  //   "50 м2", а не как случайное слово на "м" рядом с цифрой "2".
  const SQM_SPECIFIC = [
    'кв\\.\\s*м\\.', 'кв\\.\\s*м', 'кв\\s*/\\s*м\\s*2', 'кв\\s*/\\s*м\\s*²',
    'м\\.\\s*кв\\.', 'квм',
  ].join('|');
  const SQM_BARE = ['м\\s*2', 'м²'].join('|');
  out = out.replace(new RegExp(`(\\d)[^\\S\\n]*(?:${SQM_SPECIFIC}|${SQM_BARE})(?![${LETTER_CLASS}])`, 'gi'), `$1${NBSP}м²`);
  out = out.replace(new RegExp(`(^|${NOT_LETTER})(?:${SQM_SPECIFIC})(?![${LETTER_CLASS}])`, 'gi'), '$1м²');
  out = out.replace(/(\d)[^\S\n]?р\.(?![A-Za-zА-ЯЁа-яё])/g, `$1${NBSP}₽`);
  out = out.replace(new RegExp(`(\\d)[^\\S\\n]?евро(?![${LETTER_CLASS}])`, 'gi'), `$1${NBSP}€`);
  out = out.replace(new RegExp(`(\\d)[^\\S\\n]?(${CURRENCY_SIGNS})`, 'g'), `$1${NBSP}$2`);
  out = out.replace(new RegExp(`(${CURRENCY_SIGNS})[^\\S\\n]+(?=\\d)`, 'g'), '$1');
  out = out.replace(new RegExp(`(\\d)[^\\S\\n]?(г\\.|гг\\.|в\\.|вв\\.)(?![${LETTER_CLASS}])`, 'g'), `$1${NBSP}$2`);
  const unitsAlt = UNITS.slice().sort((a, b) => b.length - a.length).join('|');
  // Граница — цифра ИЛИ "+" сразу после цифры ("1 500+ человек" — "+" здесь
  // значит "и больше", не арифметика): без этого допущения число с "+"
  // просто не находится этим правилом (последний символ перед пробелом —
  // "+", а не цифра), и пробел между "1 500+" и "человек" остаётся обычным,
  // хотя по смыслу это всё то же самое "число+единица", что не должно
  // рваться при переносе строки.
  out = out.replace(new RegExp(`(\\d\\+?)[^\\S\\n]?(${unitsAlt})(?![${LETTER_CLASS}])`, 'g'), `$1${NBSP}$2`);
  // Общее правило, а не словарь: число не должно отрываться от СЛЕДУЮЩЕГО ЗА
  // НИМ слова при переносе строки — неважно, что это за слово ("по 9
  // параметрам", "5 книг", "12 часов"). Предыдущая версия ловила только
  // слова из курируемого списка UNITS — на реальном тексте это означает, что
  // с любым словом, которого нет в списке, число всё ещё может оторваться
  // при переносе. Здесь — ровно тот же пробел, что мы уже разрешили дважды.
  // Обязателен СУЩЕСТВУЮЩИЙ пробельный символ между цифрой и буквой (не
  // "[^\S\n]?", а "[^\S\n]" без "?") — переводим его в неразрывный, но не
  // вставляем пробел там, где его не было вовсе. Это отличает "по 9
  // параметрам" (пробел уже стоял) от слитных акронимов вида "3D"/"4K"
  // (цифра и буква склеены без пробела нарочно, вставлять туда пробел —
  // ломать акроним). Вставка пробела в слитную форму остаётся точечной
  // (UNITS выше) — там короткий курируемый список единиц, где слитное
  // написание почти всегда просто пропущенный пробел, а не устойчивый
  // акроним.
  out = out.replace(new RegExp(`(\\d)[^\\S\\n](?=[${LETTER_CLASS}])`, 'g'), `$1${NBSP}`);
  // Сложение между числами — пробелы вокруг "+" нормализуются до неразрывных
  // с обеих сторон, сколько бы их ни было исходно (в т.ч. ни одного): "420+ 28"
  // → "420 + 28" (пробел неразрывный, оператор не отрывается от чисел при
  // переносе строки). Умножение "*" и деление "/" сознательно не трогаем —
  // не расширять правило дальше запрошенного: "*" в обычном тексте слишком
  // часто значит не "умножить" (сноска, выделение в духе markdown), а не
  // арифметику, и однозначного сигнала "это умножение" тут нет, в отличие
  // от "+", у которого другого чтения между двумя числами практически нет.
  // Граница — цифра ИЛИ символ валюты с любой стороны ("448 €+ 334 €"): к
  // этому моменту валюта после числа уже нормализована в "числоNBSP€" (см.
  // выше), поэтому "+" здесь стоит прямо после "€", а не после цифры —
  // правило только на \d его бы просто не заметило.
  // "[^\S\n]" вместо "\s" здесь и в "="/"÷" ниже — почти та же причина, что
  // и у валют выше (пробел вокруг оператора мог оказаться уже неразрывным
  // или другим юникодовым пробельным символом, литеральный " "/"\t" его не
  // матчит), НО с одним отличием: "\s" сам по себе матчит ещё и перенос
  // строки, а перенос — это граница АБЗАЦА, не пробел внутри одной формулы.
  // Баг: телефон вида "+7 (953) 837-14-29", если несколько таких лежат
  // подряд по одному на абзац, начинается с "+" — "\s*\+\s*" через "\s",
  // включающий "\n", склеивал последнюю цифру одного абзаца с "+7" из
  // начала следующего, стирая перенос строки между ними и превращая весь
  // блок в одну строку через " + ". "[^\S\n]" — то же самое (любой
  // пробельный символ, включая NBSP), но без \n.
  out = out.replace(new RegExp(`([\\d${CURRENCY_CLASS}])[^\\S\\n]*\\+[^\\S\\n]*(?=[\\d${CURRENCY_CLASS}])`, 'g'), `$1${NBSP}+${NBSP}`);
  // "=" — как и "÷" ниже, граница ЛЮБОЙ непробельный символ, не только
  // цифра/валюта: "участников=твой гонорар" → "участников = твой гонорар"
  // (операнд слева — целое слово, не число). Исключение — сам "=" не трогаем,
  // если он соседствует с "<", ">", "!" или ещё одним "=" (т.е. это "==",
  // "!=", "<=", ">=") — похоже на сравнение из кода, а не на равенство из
  // текста, и лишний пробел внутри такого оператора всё сломает.
  out = out.replace(/(\S)[^\S\n]*=[^\S\n]*(?=\S)/g, (m, prev, offset, str) => {
    if (/[<>=!]/.test(prev)) return m;
    if (str[offset + m.length] === '=') return m;
    return `${prev}${NBSP}=${NBSP}`;
  });
  // "÷" — деление, всегда однозначно арифметика (в отличие от "*"/"/", у
  // которых полно неарифметических значений в обычном тексте, поэтому их не
  // трогаем нигде в этом файле). Граница — ЛЮБОЙ непробельный символ с обеих
  // сторон, а не только цифра/валюта: операнды формулы часто сами не числа,
  // а плейсхолдеры в квадратных скобках ("[доход]÷[участников]" →
  // "[доход] ÷ [участников]").
  out = out.replace(/(\S)[^\S\n]*÷[^\S\n]*(?=\S)/g, `$1${NBSP}÷${NBSP}`);
  // Разряды многозначных чисел — группируем по три цифры с конца неразрывным
  // пробелом, ДАЖЕ если исходно пробелов не было вовсе: "12123743" →
  // "12 123 743", "5000 €" → "5 000 €". Раньше это правило намеренно
  // трогало только уже существующие пробелы (см. комментарий ниже) — боялись
  // случайно разбить на тройки телефон или код/ID. Это всё ещё риск (номер
  // телефона без форматирования тоже попадёт под группировку), но
  // пользователь явно попросил группировать любое многозначное число, и это
  // осознанный компромисс, а не недосмотр.
  // Негативный lookbehind на «#» + hex-символы: иначе цифры внутри цветового кода
  // читаются как число и разбиваются разрядом (#E30611 → «#E30 611»).
  out = out.replace(/(?<!#[0-9A-Fa-f]{0,5})\d{1,3}(?: \d{3})+/g, (m) => m.replace(/ /g, NBSP));
  // Ровно 4 цифры подряд НЕ группируем вообще — это диапазон, в котором живут
  // почти все года (1000–2999), а определить по контексту, что число — год,
  // надёжно нельзя: рядом не всегда есть слово-подсказка ("году", "века"),
  // предлог тоже необязателен ("Основана в 1990." vs просто "1990" в
  // подписи/таблице). Раньше здесь была эвристика по слову справа — она
  // ломалась в любом случае без этого слова. Компромисс проще и надёжнее:
  // 4-значные числа всегда остаются как есть, группировка начинается с 5
  // цифр ("20202" → "20 202"), где риск случайно задеть год уже намного ниже.
  // Ведущий ноль — почти наверняка код/серийный номер (лицензия,
  // сертификат, артикул), а не количество: "№РОСС RU РГР ТОС 27.01 АН
  // 00978" — реальное число так не пишут, "00978" единиц чего-либо не
  // бывает. Настоящая величина с ведущим нулём в обычном тексте практически
  // не встречается, поэтому это дешёвый и надёжный признак "не группировать".
  out = out.replace(/(?<!#[0-9A-Fa-f]{0,5})\d{5,}/g, (m) => (m[0] === '0' ? m : m.replace(/\B(?=(\d{3})+(?!\d))/g, NBSP)));
  return out;
}

// ИНН/ОГРН(ИП)/КПП/СНИЛС и почтовый индекс после "Адрес:" — это коды, не
// число для арифметики: группировка по разрядам (см. fixNumbers выше) их
// только портит. Реальный код часто приходит уже разбитым по три цифры —
// с визитки, из формы заявки, из старой копипасты — а обычная группировка
// чисел (правило "уже есть пробелы" в fixNumbers) такую разбивку принимает
// за настоящую и просто меняет пробелы на неразрывные, не трогая структуру.
// Единственно верный вид кода — сплошная строка цифр без единого пробела,
// поэтому здесь пробелы ВНУТРИ кода убираются, а не расставляются.
// Лукбехайнд — метка сразу перед цифрами (двоеточие/пробел, не больше 4
// символов между меткой и первой цифрой) — не трогает произвольные числа
// в остальном тексте, только то, что явно подписано. "Адрес" — частный
// случай: индекс это первые несколько цифр сразу после метки, а остаток
// адреса за запятой цифровую последовательность уже не продолжает —
// шаблон сам останавливается на первом нецифровом символе.
const ID_LABEL_ALT = 'ИНН|ОГРНИП|ОГРН|КПП|СНИЛС|Адрес';
const ID_DIGITS_RE = new RegExp(`(?<=(?:${ID_LABEL_ALT})[:\\s]{0,4})\\d(?:[ ${NBSP}]?\\d){3,}`, 'giu');
// Почтовый индекс БЕЗ метки "Адрес:" — российский адрес традиционно
// открывается индексом первым, без подписи: "676805, Амурская область,
// г. Белогорск, ...". Ровно 6 цифр — индекс в РФ всегда шестизначный, не
// больше и не меньше, — сразу в начале абзаца/строки и сразу перед запятой.
// Оба якоря вместе (ровно 6 цифр + запятая сразу после) отсекают случайное
// число в начале текста: обычный текст так не начинается, а вот порядок
// "ИНДЕКС, регион, город, улица" — стандартная форма адреса.
const POSTAL_INDEX_RE = new RegExp(`(^|\\n)(\\d[ ${NBSP}]?\\d[ ${NBSP}]?\\d[ ${NBSP}]?\\d[ ${NBSP}]?\\d[ ${NBSP}]?\\d)(?=,)`, 'gu');

function fixIdCodes(text) {
  let out = text.replace(ID_DIGITS_RE, (m) => m.replace(new RegExp(`[ ${NBSP}]`, 'g'), ''));
  out = out.replace(POSTAL_INDEX_RE, (m, pre, digits) => pre + digits.replace(new RegExp(`[ ${NBSP}]`, 'g'), ''));
  return out;
}

function fixInitials(text) {
  let out = text;
  // "И. И. Иванов" — оба инициала
  out = out.replace(new RegExp(`(^|${NOT_LETTER})([А-ЯЁ])\\.[ ]+([А-ЯЁ])\\.[ ]+(?=[А-ЯЁ][а-яё])`, 'gu'),
    (_m, p1, a, b) => `${p1}${a}.${NBSP}${b}.${NBSP}`);
  // "И. Иванов" — один инициал
  out = out.replace(new RegExp(`(^|${NOT_LETTER})([А-ЯЁ])\\.[ ]+(?=[А-ЯЁ][а-яё]{2,})`, 'gu'),
    (_m, p1, a) => `${p1}${a}.${NBSP}`);
  return out;
}

// Токенизация на слова и «щели» между ними — надёжнее, чем regex-lookbehind,
// и не ломается на кириллице (см. комментарий про \b выше).
//
// «Щель» между словами — не всегда один пробел: токенизатор склеивает
// пробел с соседней пунктуацией в один «нелетерный» токен («не «слово»» →
// ["не", " «", "слово", "»", ...] — гэп после "не" это " «", а не " "), так
// строгое tokens[i+1] === ' ' пропускало "не" перед словом в кавычках/скобках.
// spaceAtStart/spaceAtEnd проверяют, что в гэпе ровно один обычный пробел,
// стоящий с нужного края (остальное — открывающая/закрывающая пунктуация),
// и правят только сам пробел внутри гэпа, не трогая пунктуацию рядом.
function fixShortWords(text) {
  const tokens = text.match(new RegExp(`[${LETTER_CLASS}0-9]+|[^${LETTER_CLASS}0-9]+`, 'g'));
  if (!tokens) return text;

  const spaceAtStart = (gap) => gap[0] === ' ' && gap.indexOf(' ', 1) === -1;
  const spaceAtEnd = (gap) => gap[gap.length - 1] === ' ' && gap.lastIndexOf(' ', gap.length - 2) === -1;

  for (let i = 0; i < tokens.length; i++) {
    const word = tokens[i];
    if (!new RegExp(`^[${LETTER_CLASS}]+$`).test(word)) continue;
    const lower = word.toLowerCase();

    // Следующее/предыдущее слово может начинаться с цифры («в 2020», «к 10») —
    // проверяем букву ИЛИ цифру, не только LETTER_RE.
    if (PREP_WORDS.has(lower)) {
      const gap = tokens[i + 1];
      const next = tokens[i + 2];
      if (gap && spaceAtStart(gap) && next && WORD_START_RE.test(next[0])) {
        tokens[i + 1] = NBSP + gap.slice(1);
      }
    }
    if (PARTICLE_WORDS.has(lower)) {
      const gap = tokens[i - 1];
      const prev = tokens[i - 2];
      if (gap && spaceAtEnd(gap) && prev && WORD_START_RE.test(prev[prev.length - 1])) {
        tokens[i - 1] = gap.slice(0, -1) + NBSP;
      }
    }
  }
  return tokens.join('');
}

// «Так как» и подобные фразы — та же токенизация, что и в fixShortWords
// выше: пробел между словами фразы становится неразрывным, только если
// слова из COMPOUND_CONJUNCTIONS стоят ПОДРЯД именно в этом порядке, а не
// просто оба встретились в тексте порознь («так» само по себе — обычное
// наречие, не часть союза).
function fixCompoundConjunctions(text) {
  const tokens = text.match(new RegExp(`[${LETTER_CLASS}0-9]+|[^${LETTER_CLASS}0-9]+`, 'g'));
  if (!tokens) return text;

  const spaceAtStart = (gap) => gap[0] === ' ' && gap.indexOf(' ', 1) === -1;

  for (const phrase of COMPOUND_CONJUNCTIONS) {
    const words = phrase.split(' ');
    for (let i = 0; i < tokens.length; i++) {
      if (tokens[i].toLowerCase() !== words[0]) continue;
      let ok = true;
      for (let w = 1; w < words.length; w++) {
        const gap = tokens[i + 2 * (w - 1) + 1];
        const word = tokens[i + 2 * w];
        if (!gap || !spaceAtStart(gap) || !word || word.toLowerCase() !== words[w]) { ok = false; break; }
      }
      if (!ok) continue;
      for (let w = 1; w < words.length; w++) {
        const gapIdx = i + 2 * (w - 1) + 1;
        tokens[gapIdx] = NBSP + tokens[gapIdx].slice(1);
      }
    }
  }
  return tokens.join('');
}

// URL защищаются от ВСЕХ правил типографики целиком, не только от дефиса
// внутри слова (хотя это самый очевидный случай: "site.com/some-page-name"
// после правила "дефис в слове → неразрывный" превращается в
// "site.com/some‑page‑name" — U+2011 вместо обычного дефиса выглядит
// идентично на глаз, но это уже другой символ, и адрес ломается). Кавычки-
// «ёлочки» и nbsp-правила для коротких слов рискуют не меньше: путь с
// кириллицей вроде "сайт.ru/на-главную" содержит токен "на", который
// fixShortWords примет за предлог и попробует приклеить неразрывным
// пробелом — внутри URL пробелов и подавно быть не должно.
// Подход — "вырезать (плейсхолдер) → прогнать всю типографику → вернуть
// оригинал на место", а не точечное исключение в каждом из полутора
// десятков правил: россыпь "но не внутри URL" по всему файлу — источник
// новых пропущенных мест при каждом следующем правиле, а не защита.
// Плейсхолдер — один символ из приватной зоны Юникода (U+E000+): такие
// кодпоинты не печатаются ни с одной клавиатуры и не встречаются в реальном
// пользовательском тексте, коллизия исключена. Без цифр в самом плейсхолдере
// специально — иначе индекс URL мог бы угодить в группировку разрядов
// (`\d{4,}` в fixNumbers) при достаточном количестве ссылок в одном слое.
// Границы совпадения — НЕ "\b": как и везде в этом файле (см. предупреждение
// в самом начале про JS \b и кириллицу), \b проверяет переход между [\w] и
// не-[\w], а кириллица в \w не входит — "\bwww" перед "сайт.ru" не сработал
// бы вообще, потому что и "конец строки/пробел" ДО, и "с" (первая буква)
// одинаково "не \w" для движка регулярных выражений, границы попросту нет.
// Негативный lookbehind с явным классом символов (латиница+кириллица+цифры)
// работает одинаково для обоих алфавитов, потому что сам задаёт нужный класс,
// а не полагается на встроенное (латинское) понятие "буквы" в \b.
const URL_RE = /(?<![A-Za-zА-ЯЁа-яё0-9])(?:https?:\/\/[^\s«»"'()[\]]+|www\.[^\s«»"'()[\]]+|[a-zA-Zа-яёА-ЯЁ0-9](?:[a-zA-Zа-яёА-ЯЁ0-9-]*[a-zA-Zа-яёА-ЯЁ0-9])?\.[a-zA-Zа-яё]{2,}\/[^\s«»"'()[\]]*)/gu;
// Хвостовая пунктуация — конец предложения ("Смотрите https://example.com."),
// закрывающая кавычка/скобка после ссылки — почти никогда не часть самого
// адреса. Обрезается от совпадения и возвращается в текст СРАЗУ, не под
// защитой: остальная типографика должна видеть эту точку/кавычку как обычную.
const URL_TRAILING_PUNCT_RE = /[.,!?;:'")\]]+$/;

function protectUrls(text) {
  const urls = [];
  const out = text.replace(URL_RE, (m) => {
    const trail = URL_TRAILING_PUNCT_RE.exec(m);
    const core = trail ? m.slice(0, m.length - trail[0].length) : m;
    const suffix = trail ? trail[0] : '';
    if (!core) return m;
    urls.push(core);
    return String.fromCodePoint(0xE000 + urls.length - 1) + suffix;
  });
  return { text: out, urls };
}

function restoreUrls(text, urls) {
  if (!urls.length) return text;
  return text.replace(/[-]/g, (ch) => {
    const idx = ch.codePointAt(0) - 0xE000;
    return idx >= 0 && idx < urls.length ? urls[idx] : ch;
  });
}

function typografize(text, opts) {
  const { text: protectedText, urls } = protectUrls(text);
  let out = protectedText;
  if (opts.ellipsis) out = fixEllipsis(out);
  if (opts.dashes) out = fixDashes(out);
  if (opts.quotes) { out = fixQuotes(out); out = fixApostrophe(out); out = stripQuoteTrailingPeriod(out); out = capitalizeAfterColonQuote(out); }
  if (opts.spaces) { out = fixSpaces(out); out = fixEmojiSpacing(out); out = fixEmoticons(out); }
  if (opts.nbsp) {
    out = fixPhone(out);
    out = fixAbbreviations(out);
    out = fixAddressAbbreviations(out);
    out = fixNumbers(out);
    out = fixIdCodes(out);
    out = fixInitials(out);
    out = fixShortWords(out);
    out = fixCompoundConjunctions(out);
  }
  out = restoreUrls(out, urls);
  return out;
}

// Ручной маркер списка "- текст" (буллет) или "1. текст"/"1) текст"
// (нумерация) в начале строки — убирает сам маркер из текста целиком
// (включая цифру: нативный ORDERED-список в Figma нумерует сам, свою цифру
// в тексте оставлять нельзя — будет задвоение "1. 1. текст"), запоминая,
// каким параграфам какой тип списка назначить (node.setRangeListOptions,
// применяется позже — только когда известны финальные индексы после правки
// текста). Ведущий отступ перед маркером НЕ сохраняется (раньше сохранялся —
// см. комментарий у самого удаления ниже, почему это ломало рендер).
//
// Нумерованный маркер конвертируется в СПИСОК ТОЛЬКО если рядом (соседний
// абзац сверху или снизу) есть ещё один такой же маркер — то есть у него
// реально есть начало или продолжение нумерации. Одиночная "2. текст" без
// соседей — не список, а цифра, поставленная намеренно (номер пункта
// договора, этаж, шаг инструкции сам по себе и т.п.): маркер остаётся
// текстом как есть, node.setRangeListOptions для неё не вызывается. Первая
// буква после маркера всё равно капитализируется как в списке — см.
// отдельный фолбэк-regex в capitalizeListParagraphs, он про капитализацию,
// не про то, стоит ли создавать список, и решает независимо. Буллета
// "- текст" эта проверка не касается — дефис в начале строки почти всегда
// осмысленный маркер даже сам по себе, и был им ещё до этой правки.
function stripListMarkers(text) {
  const paras = text.split('\n');
  const types = paras.map(() => null); // null | 'UNORDERED' | 'ORDERED'
  const numberedRe = /^(\s*)\d+[.)][ \t]+(?=\S)/;
  const isNumbered = paras.map((p) => numberedRe.test(p));

  const stripped = paras.map((p, i) => {
    const dash = /^(\s*)-[ \t]+(?=\S)/.exec(p);
    if (dash) {
      types[i] = 'UNORDERED';
      // Ведущий отступ (dash[1]) НЕ сохраняется — раньше он приклеивался
      // обратно перед текстом пункта ("  " + "текст"), и именно этот
      // оставшийся пробел ломал рендер настоящего Figma-списка: номер/буллет
      // отрывался на свою строку, а текст пункта переносился ниже
      // неиндентированным (воспроизведено и при LEFT-выравнивании тоже —
      // значит дело было не в выравнивании, а именно в этом символе).
      // У нативного списка Figma отступ — свойство параграфа, не текст;
      // хранить его буквальным пробелом внутри содержимого пункта не нужно
      // и, как выяснилось, опасно.
      return p.slice(dash[0].length);
    }
    if (isNumbered[i]) {
      const hasNeighbor = (i > 0 && isNumbered[i - 1]) || (i < paras.length - 1 && isNumbered[i + 1]);
      if (hasNeighbor) {
        const numbered = numberedRe.exec(p);
        types[i] = 'ORDERED';
        return p.slice(numbered[0].length);
      }
    }
    return p;
  });
  return { text: stripped.join('\n'), types };
}

// Ставит буллет- или нумерованный список только тем параграфам, для которых
// stripListMarkers нашла и убрала маркер — индексы считаются по УЖЕ финальному
// тексту узла, поэтому вызывается после applyTypography, когда
// node.characters === newText.
function applyListMarkers(node, text, types) {
  let start = 0;
  const paras = text.split('\n');
  for (let i = 0; i < paras.length; i++) {
    const para = paras[i];
    if (types[i] && para.length > 0) {
      node.setRangeListOptions(start, start + para.length, { type: types[i] });
    }
    start += para.length + 1;
  }
}

// Устойчивые формулировки согласий («обработку персональных данных»,
// «политику конфиденциальности») в макетах принято подчёркивать — обычно
// это ссылка на юридический документ, даже когда самой ссылки в Figma нет.
// Курируемый список КОНКРЕТНЫХ словоформ, не regex на произвольное падежное
// склонение — со склонениями легко случайно подчеркнуть кусок соседнего
// слова в юридическом тексте (там много похожих оборотов). Расширяется
// прямо здесь, тем же принципом, что и другие курируемые списки в файле
// (PREP_WORDS, UNITS, ABBREV_TAIL_WORDS).
const UNDERLINE_PHRASES = [
  'обработку персональных данных', 'обработка персональных данных',
  'обработке персональных данных', 'обработкой персональных данных',
  'политику конфиденциальности', 'политика конфиденциальности',
  'политике конфиденциальности', 'политикой конфиденциальности',
];

// Индексы всех вхождений фраз из UNDERLINE_PHRASES в тексте — поиск
// регистронезависимый (текст мог начинаться с заглавной после капитализации
// пункта списка выше), сами индексы — по оригинальному тексту с сохранением
// регистра. Пересекающиеся совпадения (одна фраза — подстрока другой при
// разных словоформах рядом) отбрасываются в пользу первой найденной.
function findUnderlineRanges(text) {
  const lower = text.toLowerCase();
  const ranges = [];
  for (const phrase of UNDERLINE_PHRASES) {
    const target = phrase.toLowerCase();
    let from = 0;
    for (;;) {
      const idx = lower.indexOf(target, from);
      if (idx === -1) break;
      ranges.push({ start: idx, end: idx + phrase.length });
      from = idx + phrase.length;
    }
  }
  ranges.sort((a, b) => a.start - b.start);
  const merged = [];
  for (const r of ranges) {
    if (merged.length && r.start < merged[merged.length - 1].end) continue;
    merged.push(r);
  }
  return merged;
}

// Применяет подчёркивание к найденным диапазонам. Пропускает уже
// подчёркнутые диапазоны (getRangeTextDecoration === 'UNDERLINE') — иначе
// повторный прогон плагина на уже готовом тексте всегда считался бы
// "изменением", раздувая счётчик в UI без реальной правки.
function applyUnderlines(node, text) {
  const ranges = findUnderlineRanges(text);
  let didChange = false;
  for (const r of ranges) {
    let current;
    try {
      current = node.getRangeTextDecoration(r.start, r.end);
    } catch (_e) {
      current = null;
    }
    if (current === 'UNDERLINE') continue;
    node.setRangeTextDecoration(r.start, r.end, 'UNDERLINE');
    didChange = true;
  }
  return didChange;
}

// Заглавная буква первого слова в пункте списка. Список — свойство параграфа
// в Figma (node.getRangeListOptions), а не текст: нативный маркированный/
// нумерованный список не оставляет в characters ни дефиса, ни точки. Поэтому
// эта функция принимает флаги "это параграф-список" отдельно (см.
// getListParagraphFlags и stripListMarkers) — определить список по одной
// лишь строке нельзя. Дополнительно распознаёт текстовый маркер "— "/"•"
// и цифровой "1."/"1)" прямо по строке — это два РАЗНЫХ решения: список
// (setRangeListOptions) для одиночной нумерованной строки stripListMarkers
// сознательно не делает (см. комментарий там), а заглавную букву после
// маркера всё равно нужно поставить — маркер синтаксически остаётся на
// месте («2. текст» → «2. Текст»), в список просто не превращается.
function capitalizeParagraph(str) {
  let i = 0;
  while (i < str.length && /\s/.test(str[i])) i++;
  if (str[i] === EM_DASH || str[i] === EN_DASH || str[i] === '-' || str[i] === '•') {
    i++;
    while (i < str.length && /\s/.test(str[i])) i++;
  } else {
    const numbered = /^\d+[.)][ \t]+/.exec(str.slice(i));
    if (numbered) {
      i += numbered[0].length;
    }
  }
  while (i < str.length && /["«»„“”'‘’(\[]/.test(str[i])) i++;
  if (i < str.length && LETTER_RE.test(str[i])) {
    return str.slice(0, i) + str[i].toUpperCase() + str.slice(i + 1);
  }
  return str;
}

function capitalizeListParagraphs(text, flags) {
  const paras = text.split('\n');
  for (let i = 0; i < paras.length; i++) {
    if (flags[i] || /^\s*([—–•-]|\d+[.)])[ ]/.test(paras[i])) {
      paras[i] = capitalizeParagraph(paras[i]);
    }
  }
  return paras.join('\n');
}

// Сокращения, у которых финальная точка — часть самого сокращения, а не
// конец предложения ("...и т. д.", "...(см. договор) Иванов И."). Список
// курируемый, пересекается со словами, которые уже понимает fixAbbreviations/
// fixNumbers/fixInitials выше по файлу, — здесь та же логика нужна отдельно,
// потому что решается другой вопрос (снимать финальную точку пункта списка
// или нет), а не расстановка неразрывного пробела.
// Второй источник — уже курируемый ADDRESS_PREFIX_ABBR (см. выше): "г.",
// "ул." и т. п. — тоже сокращения, требующие точки как части себя, а не как
// конца предложения. Единицы измерения (UNITS) сюда намеренно НЕ идут: это
// обычные слова ("человек", "рублей"), а не сокращения, — точка после них в
// конце пункта списка почти всегда действительно завершает предложение.
const ABBREV_TAIL_WORDS = new Set([
  'д', 'п', 'е', 'к', 'др', 'пр', 'проч', 'см', 'напр', 'г', 'гг', 'в', 'вв',
  ...ADDRESS_PREFIX_ABBR,
]);

function endsWithAbbreviation(str) {
  const m = new RegExp(`[${LETTER_CLASS}]+\\.$`).exec(str);
  if (!m) return false;
  const word = m[0].slice(0, -1);
  // Одна заглавная буква в конце — инициал ("Иванов И."), не конец фразы.
  if (word.length === 1 && LETTER_RE.test(word) && word === word.toUpperCase()) return true;
  return ABBREV_TAIL_WORDS.has(word.toLowerCase());
}

// Точка в конце пункта списка — лишняя: раз это конец пункта, а не начало
// нового предложения внутри него же, финальная точка типографически не
// нужна (общепринятое оформление списков — короткие пункты без точки в
// конце). Точки ВНУТРИ пункта, где после них идёт новое предложение
// ("...сторителлинга. Люди не влюбились..."), не трогаем — обрезается
// только самый последний символ абзаца, и только если это одиночная точка:
// многоточие (буквальное "..." — например, при выключенном правиле
// «Многоточие» — или уже свёрнутое в «…») не задевается, как и сокращения
// из endsWithAbbreviation.
function stripListTrailingPeriod(text, flags) {
  const paras = text.split('\n');
  for (let i = 0; i < paras.length; i++) {
    if (!flags[i]) continue;
    const p = paras[i];
    if (p.endsWith('.') && !p.endsWith('..') && !endsWithAbbreviation(p)) {
      paras[i] = p.slice(0, -1);
    }
  }
  return paras.join('\n');
}

// Точка перед закрывающей кавычкой — тот же принцип, что и в конце пункта
// списка выше (stripListTrailingPeriod): закрывающая «» сама подводит
// черту, финальная точка внутри — «Текст.» → «Текст» — визуально лишняя.
// Работает по ВСЕМУ тексту, а не только в списках: кавычки — самостоятельная
// типографская единица независимо от того, список это или нет. "Последнее
// предложение" — буквально: если внутри кавычек несколько предложений
// («Первое. Второе.»), убирается только последняя точка перед »,
// внутренняя («Первое.») остаётся — как и в списках, задет только самый
// конец. Не трогает сокращения (endsWithAbbreviation) и многоточие.
// Не различает вложенные кавычки — тот же один уровень, что и в fixQuotes.
function stripQuoteTrailingPeriod(text) {
  return text.replace(/«([^«»]*)»/g, (m, inner) => {
    if (inner.endsWith('.') && !inner.endsWith('..') && !endsWithAbbreviation(inner)) {
      return `«${inner.slice(0, -1)}»`;
    }
    return m;
  });
}

// Паттерн "подпись: «цитата»" (частый в карточках/слайдах — «Клиент:
// «отлично сработали»») — первая буква внутри кавычек становится заглавной,
// если она строчная: ": «текст»" → ": «Текст»". Двоеточие и открывающая
// «ёлочка» — обязательный якорь, чтобы не трогать кавычки без двоеточия
// перед ними (там своя типографика, не эта). Уже заглавная буква не
// матчится классом [a-zа-яё] — regex просто не сработает, менять нечего.
function capitalizeAfterColonQuote(text) {
  return text.replace(/:([^\S\n]*)«([^\S\n]*)([a-zа-яё])/gu, (_m, gap1, gap2, ch) => `:${gap1}«${gap2}${ch.toUpperCase()}`);
}

const CLOSING_PUNCT_RE = /["'»)\]”’]/;

function isAbbreviationWord(word) {
  if (!word) return false;
  if (word.length === 1 && LETTER_RE.test(word) && word === word.toUpperCase()) return true;
  return ABBREV_TAIL_WORDS.has(word.toLowerCase());
}

// Проверяет, настоящий ли это конец предложения, а не часть сокращения или
// десятичной дроби. Слово перед точкой ищется с ПРОПУСКОМ закрывающей
// пунктуации (кавычки, скобки) — без этого пропуска точка после
// «...мистика».» осталась бы незамеченной: между последней буквой слова и
// точкой стоит "»", а не сама буква, и простой regex "буквы+точка" такую
// точку просто не находит (m[0] тогда null) — ровно так родился баг, из-за
// которого текст с двумя предложениями («...выбирать — «или наука, или
// мистика». Мы можем дышать...») ошибочно считался «одним предложением».
function isSentenceEndingPeriod(str, idx) {
  if (str[idx - 1] === '.' || str[idx + 1] === '.') return false; // часть ".." / многоточия
  if (/\d/.test(str[idx - 1] || '') && /\d/.test(str[idx + 1] || '')) return false; // десятичная дробь

  let j = idx - 1;
  while (j >= 0 && CLOSING_PUNCT_RE.test(str[j])) j--;
  const wordEnd = j + 1;
  while (j >= 0 && LETTER_RE.test(str[j])) j--;
  const word = str.slice(j + 1, wordEnd);

  return !isAbbreviationWord(word);
}

// Точка в конце убирается и вне списков/кавычек — если ВЕСЬ текстовый узел
// целиком: (а) один абзац, без переноса строки ('\n' — уже "продолжение на
// новой строке", условие явно исключает это); (б) содержит РОВНО одно
// предложение. Короткие карточки-утверждения, цитаты-колл-ауты, заголовки —
// тот же принцип, что уже применяется к пункту списка и к тексту в кавычках
// (см. stripListTrailingPeriod/stripQuoteTrailingPeriod выше): раз дальше
// текста нет, финальная точка визуально лишняя.
// "Одно предложение" проверяется посимвольным сканом — ищем ЛЮБУЮ точку в
// теле текста и для каждой спрашиваем isSentenceEndingPeriod. Если хоть одна
// оказалась настоящей (не сокращением) — предложений больше одного, текст не
// трогаем вообще: это уже обычная проза, не короткое утверждение.
function stripSingleSentenceTrailingPeriod(text) {
  if (text.includes('\n')) return text;
  if (!text.endsWith('.') || text.endsWith('..')) return text;
  if (endsWithAbbreviation(text)) return text;

  const body = text.slice(0, -1);
  if (/[!?]/.test(body)) return text;

  for (let i = 0; i < body.length; i++) {
    if (body[i] === '.' && isSentenceEndingPeriod(body, i)) return text;
  }

  return body;
}

// Параграфы разделены '\n', и ни одно правило типографики не добавляет
// и не убирает '\n' — поэтому список флагов, собранный на СТАРОМ тексте
// (пока метаданные Figma ещё доступны на исходных индексах), остаётся
// синхронным с параграфами уже изменённого текста по позиции в массиве.
function getListParagraphFlags(node, text) {
  const flags = [];
  let start = 0;
  for (const para of text.split('\n')) {
    let isList = false;
    if (start < text.length) {
      try {
        const listOptions = node.getRangeListOptions(start, start + 1);
        isList = listOptions !== figma.mixed && listOptions.type !== 'NONE';
      } catch (_e) {
        isList = false;
      }
    }
    flags.push(isList);
    start += para.length + 1;
  }
  return flags;
}

