// Счётчик выделения в шапке UI пересобирает этот список на КАЖДЫЙ
// selectionchange, поэтому обход должен быть дешёвым: findAllWithCriteria
// отдаёт все текстовые слои поддерева одним вызовом через мост в Figma, тогда
// как ручная рекурсия дёргает node.children на каждом узле (у фрейма на пару
// тысяч слоёв это заметная пауза при каждом клике по холсту). Рекурсия
// остаётся запасным путём для типов узлов без этого метода.
function collectTextNodes(nodes) {
  const result = [];
  const seen = new Set();
  const push = (node) => {
    if (seen.has(node.id)) return;
    seen.add(node.id);
    result.push(node);
  };
  function visit(node) {
    if (node.type === 'TEXT') {
      push(node);
      return;
    }
    if (typeof node.findAllWithCriteria === 'function') {
      for (const text of node.findAllWithCriteria({ types: ['TEXT'] })) push(text);
      return;
    }
    if ('children' in node) {
      for (const child of node.children) visit(child);
    }
  }
  for (const node of nodes) visit(node);
  return result;
}

async function loadFontsForNode(node) {
  if (node.characters.length === 0) return;
  const segments = node.getStyledTextSegments(['fontName']);
  const seen = new Set();
  for (const seg of segments) {
    const key = `${seg.fontName.family}::${seg.fontName.style}`;
    if (seen.has(key)) continue;
    seen.add(key);
    await figma.loadFontAsync(seg.fontName);
  }
}

// Дифф внутри ОДНОГО абзаца — возвращает МИНИМАЛЬНЫЙ набор непересекающихся
// правок, а не один сплошной диапазон. Это важно, когда в абзаце меняются
// сразу два места (например, кавычка в начале и неразрывный пробел ближе к
// концу): между ними в тексте может проходить граница разного оформления
// символов — заливка/прозрачность части текста (частый паттерн вёрстки:
// приглушённое описание + выделенное слово). Один общий диапазон
// удаления/вставки стёр бы эту границу, откатив всё к одному унаследованному
// стилю — ровно то, что раньше приводило к «половина текста стала одного
// цвета». Раздельные хунки трогают только реально изменившиеся символы,
// оставляя всё остальное, включая границы стилей между правками, нетронутым.
//
// Алгоритм — Майерс (греди + трасса), а не Вагнер—Фишер, который стоял здесь
// раньше. Причина в стоимости: WF всегда платит O(n×m) временем И памятью,
// сколько бы символов реально ни изменилось. Типографика же правит единицы
// процентов текста, поэтому Майерс с его O((n+m)·D), где D — число реальных
// правок, на том же материале дешевле в разы: замеры на сгенерированных
// русских текстах дали 8× на 200 символах и 18× на 5000, а по памяти — 13 МБ
// против 256 МБ в худшем случае на 8000 символов. Именно из-за квадратичной
// стоимости WF здесь стоял порог в 600 символов, выше которого абзац уходил
// на грубый prefix/suffix-дифф и терял ровно те границы оформления, ради
// которых всё это писалось. С Майерсом порог не нужен — он снят.
const MYERS_MAX_D = 2000; // предел числа правок на один проход, см. collectHunks

// Хунки в ЛОКАЛЬНЫХ координатах a. false — правок больше, чем разрешает maxD.
function myersHunks(a, b, maxD) {
  const n = a.length;
  const m = b.length;
  const max = n + m;
  const offset = max;
  const v = new Int32Array(2 * max + 1);
  const trace = [];
  let dFinal = -1;

  const limit = Math.min(max, maxD);
  outer:
  for (let d = 0; d <= limit; d++) {
    // Снимок только рабочего окна диагоналей (2d+1), а не всей полосы:
    // иначе трасса весит O(D·(n+m)) — на переписанном тексте это сотни
    // мегабайт и гарантированная смерть песочницы плагина.
    trace.push(v.slice(offset - d, offset + d + 1));
    for (let k = -d; k <= d; k += 2) {
      let x;
      if (k === -d || (k !== d && v[offset + k - 1] < v[offset + k + 1])) x = v[offset + k + 1];
      else x = v[offset + k - 1] + 1;
      let y = x - k;
      while (x < n && y < m && a[x] === b[y]) { x++; y++; }
      v[offset + k] = x;
      if (x >= n && y >= m) { dFinal = d; break outer; }
    }
  }

  if (dFinal < 0) return false;

  // Обратный проход по снимкам — восстанавливаем сами правки.
  const edits = [];
  let x = n;
  let y = m;
  for (let d = dFinal; d > 0; d--) {
    const snap = trace[d];
    const at = (kk) => snap[kk + d];
    const k = x - y;
    const prevK = (k === -d || (k !== d && at(k - 1) < at(k + 1))) ? k + 1 : k - 1;
    const prevX = at(prevK);
    const prevY = prevX - prevK;
    while (x > prevX && y > prevY) { x--; y--; }   // общий фрагмент
    if (x > prevX) { edits.push({ del: true, x: x - 1, y }); x--; }
    else { edits.push({ del: false, x, y: y - 1 }); y--; }
  }
  edits.reverse();

  // Соседние правки сливаем в один хунк — иначе на каждую подменённую букву
  // придётся отдельная пара deleteCharacters/insertCharacters.
  const hunks = [];
  let cur = null;
  for (const e of edits) {
    if (e.del) {
      if (cur && cur.oldEnd === e.x) { cur.oldEnd = e.x + 1; continue; }
      if (cur) hunks.push(cur);
      cur = { oldStart: e.x, oldEnd: e.x + 1, insertText: '' };
    } else {
      if (cur && cur.oldEnd === e.x) { cur.insertText += b[e.y]; continue; }
      if (cur) hunks.push(cur);
      cur = { oldStart: e.x, oldEnd: e.x, insertText: b[e.y] };
    }
  }
  if (cur) hunks.push(cur);
  return hunks;
}

function collectHunks(a, b, base, out) {
  // Общий префикс и суффикс отрезаем до основного алгоритма: у типографской
  // правки это почти весь абзац, а D падает вместе с ним.
  let lo = 0;
  const maxLo = Math.min(a.length, b.length);
  while (lo < maxLo && a[lo] === b[lo]) lo++;
  let hi = 0;
  const maxHi = maxLo - lo;
  while (hi < maxHi && a[a.length - 1 - hi] === b[b.length - 1 - hi]) hi++;

  const aa = a.slice(lo, a.length - hi);
  const bb = b.slice(lo, b.length - hi);
  const nb = base + lo;

  if (!aa.length && !bb.length) return;
  if (!aa.length) { out.push({ oldStart: nb, oldEnd: nb, insertText: bb }); return; }
  if (!bb.length) { out.push({ oldStart: nb, oldEnd: nb + aa.length, insertText: '' }); return; }

  const hunks = myersHunks(aa, bb, MYERS_MAX_D);
  if (hunks) {
    for (const h of hunks) out.push({ oldStart: h.oldStart + nb, oldEnd: h.oldEnd + nb, insertText: h.insertText });
    return;
  }

  // Предохранитель: правок больше лимита — текст переписан целиком, а не
  // оттипографирован (правила выше столько изменить физически не могут).
  // Режем пополам и считаем части отдельно. Хунков выйдет больше, чем
  // минимально возможно, но каждый по-прежнему точечный — грубого «одного
  // диапазона на весь абзац», который стирает границы оформления, здесь нет.
  const ma = aa.length >> 1;
  // Делить нечего (кусок в один символ) — заменяем его целиком. Без этого
  // выхода рекурсия ушла бы в бесконечный цикл на одном и том же куске.
  if (ma === 0) { out.push({ oldStart: nb, oldEnd: nb + aa.length, insertText: bb }); return; }
  const mb = Math.round(bb.length * (ma / aa.length));
  collectHunks(aa.slice(0, ma), bb.slice(0, mb), nb, out);
  collectHunks(aa.slice(ma), bb.slice(mb), nb + ma, out);
}

function diffHunks(oldText, newText) {
  if (oldText === newText) return [];
  const out = [];
  collectHunks(oldText, newText, 0, out);
  return out;
}

// Диф и правка ПО АБЗАЦАМ, а не по всему тексту сразу — и ВНУТРИ абзаца по
// отдельным хункам (diffHunks), а не одним диапазоном. Список — свойство
// параграфа в Figma; если найти единственный изменившийся фрагмент по всему
// тексту (старый способ) и он случайно охватывает несколько абзацев (правка
// нужна в первом и третьем — диапазон захватывает и второй, хотя тот не
// менялся), deleteCharacters/insertCharacters пересоздаёт символы внутри
// ЧУЖИХ переносов строк — Figma расценивает это как новый абзац и сбрасывает
// его параграфное форматирование (в том числе уже стоявший маркированный
// список). Различая абзацы отдельно, мы никогда не задеваем '\n' и содержимое
// абзацев, которые не изменились, — их listOptions остаются как есть.
async function applyTypography(node, newText) {
  const oldText = node.characters;
  if (oldText === newText) return false;

  await loadFontsForNode(node);

  const oldParas = oldText.split('\n');
  const newParas = newText.split('\n');

  const starts = [];
  let acc = 0;
  for (const p of oldParas) {
    starts.push(acc);
    acc += p.length + 1;
  }

  let changed = false;
  // Назад — чтобы уже применённая правка в одном абзаце (или хунке) не
  // сдвигала индексы того, что обрабатывается следом.
  for (let i = oldParas.length - 1; i >= 0; i--) {
    const oldP = oldParas[i];
    const newP = newParas[i];
    if (oldP === newP) continue;
    changed = true;

    const hunks = diffHunks(oldP, newP);
    for (let h = hunks.length - 1; h >= 0; h--) {
      const { oldStart, oldEnd, insertText } = hunks[h];
      const absStart = starts[i] + oldStart;
      const absEnd = starts[i] + oldEnd;

      if (absEnd > absStart) node.deleteCharacters(absStart, absEnd);
      if (insertText.length) {
        const useStyle = absStart === 0 ? 'AFTER' : 'BEFORE';
        node.insertCharacters(absStart, insertText, useStyle);
      }
    }
  }

  return changed;
}

const DEFAULT_OPTS = { nbsp: true, dashes: true, quotes: true, ellipsis: true, spaces: true, lists: true, underline: true };
// Верхняя граница длины слоя. При квадратичном дифе она стояла на 5000 и была
// защитой от подвисания; с Майерсом такой слой стоит десятки миллисекунд,
// поэтому граница поднята и осталась только страховкой от вырожденных данных
// (весь роман в одном текстовом слое). Слои длиннее пропускаются со счётчиком,
// а не молча.
const MAX_NODE_LENGTH = 50000;
const OPTS_KEY = 'opts';

// Сколько слоёв обрабатываем между передышками. Песочница плагина
// однопоточная: пока наш цикл не вернёт управление, Figma не отрисует ни
// прогресс, ни нажатие «Остановить», а на большом выделении сочтёт плагин
// зависшим. Пауза через setTimeout — настоящий макротаск, в отличие от await
// на уже загруженном шрифте, который резолвится микрозадачей и цикл событий
// не отпускает. 25 — компромисс: на глаз прогресс идёт плавно, а накладные
// расходы на паузы теряются на фоне самой работы.
const YIELD_EVERY = 25;
const yieldToEventLoop = () => new Promise((resolve) => setTimeout(resolve, 0));

// Взводится сообщением от кнопки «Остановить» и проверяется между слоями.
let stopRequested = false;
let running = false;

// Галочки правил переживают перезапуск плагина: отключил «Списки» один раз —
// он останется отключённым и завтра. Значения из хранилища прогоняются через
// DEFAULT_OPTS, поэтому новое правило, добавленное в следующей версии, у
// старого пользователя окажется включённым, а не пропавшим.
async function loadOpts() {
  try {
    const saved = await figma.clientStorage.getAsync(OPTS_KEY);
    return Object.assign({}, DEFAULT_OPTS, saved || {});
  } catch (_e) {
    return Object.assign({}, DEFAULT_OPTS);
  }
}

async function saveOpts(opts) {
  try {
    await figma.clientStorage.setAsync(OPTS_KEY, Object.assign({}, DEFAULT_OPTS, opts || {}));
  } catch (_e) {
    // Настройки — не критичные данные: не смогли сохранить, работаем дальше.
  }
}

// Живое состояние выделения для шапки UI: сколько текстовых слоёв попадёт под
// правку. До этого пользователь узнавал про пустое выделение только по ошибке
// после клика — теперь кнопка запуска просто неактивна, пока нечего править.
function describeSelection() {
  const selection = figma.currentPage.selection;
  let count = 0;
  try {
    count = collectTextNodes(selection).length;
  } catch (_e) {
    count = 0;
  }
  return { count, hasSelection: selection.length > 0 };
}

const postSelection = () => figma.ui.postMessage(Object.assign({ type: 'selection' }, describeSelection()));

figma.on('selectionchange', postSelection);
figma.on('currentpagechange', postSelection);

figma.ui.onmessage = async (msg) => {
  // UI сообщает о готовности сам — постить состояние раньше, чем загрузился
  // iframe, бесполезно: сообщение просто некому принять.
  if (msg.type === 'ready') {
    const opts = await loadOpts();
    figma.ui.postMessage(Object.assign({ type: 'init', opts }, describeSelection()));
    return;
  }

  if (msg.type === 'opts') {
    await saveOpts(msg.opts);
    return;
  }

  if (msg.type === 'stop') {
    stopRequested = true;
    return;
  }

  if (msg.type === 'run') {
    // Повторный запуск поверх идущего сломал бы счётчики и дал бы двойную
    // правку одного слоя — кнопка в UI на это время выключена, но сообщение
    // может прийти и по Enter.
    if (running) return;

    const opts = Object.assign({}, DEFAULT_OPTS, msg.opts || {});
    await saveOpts(opts);
    const selection = figma.currentPage.selection;

    if (!selection.length) {
      figma.ui.postMessage({ type: 'result', ok: false, error: 'Ничего не выбрано. Выделите текст или фрейм с текстом.' });
      return;
    }

    const nodes = collectTextNodes(selection);
    if (!nodes.length) {
      figma.ui.postMessage({ type: 'result', ok: false, error: 'В выделении нет текстовых слоёв.' });
      return;
    }

    running = true;
    stopRequested = false;
    let changed = 0;
    let skipped = 0;
    let processed = 0;
    let stopped = false;
    let fatal = null;
    // Счётчик "пропущено" в UI не говорит, КАКОЙ слой и ПОЧЕМУ — этого не
    // хватает, если разбираться, что вообще пошло не так. Имя слоя + причина
    // копятся здесь и уходят в 'result' вместе с остальными счётчиками —
    // ui.html раскрывает список по клику, без консоли разработчика.
    const skippedDetails = [];
    figma.ui.postMessage({ type: 'progress', done: 0, total: nodes.length, changed: 0 });

    // Сбой отдельного слоя ловится внутри цикла и идёт в счётчик пропущенных.
    // Этот try — про другое: что угодно системное, упавшее ВНЕ обработки слоя,
    // оставило бы running взведённым навсегда, а UI — с полосой прогресса и
    // кнопкой «Остановить», которая уже ничего не останавливает. Плагин
    // выглядел бы намертво зависшим, хотя достаточно вернуть его в покой.
    try {
      for (const node of nodes) {
        if (stopRequested) { stopped = true; break; }
        try {
          if (node.characters.length > MAX_NODE_LENGTH) {
            skipped++;
            skippedDetails.push({ name: node.name, reason: `слишком длинный текст (${node.characters.length} символов, лимит ${MAX_NODE_LENGTH})` });
            continue;
          }

          const oldText = node.characters;

          // Ручной маркер "- " или "1. " снимается ДО typografize — иначе
          // fixDashes успеет превратить дефис в текстовый "— " раньше, чем мы
          // решим, что здесь нужен настоящий список Figma, а не символ в тексте.
          let workingText = oldText;
          let manualTypes = null;
          if (opts.lists) {
            const stripped = stripListMarkers(workingText);
            workingText = stripped.text;
            manualTypes = stripped.types;
          }

          // Параграфы, уже оформленные как список средствами самой Figma —
          // считываем на старом тексте, пока индексы ещё соответствуют текущему
          // состоянию узла (только для запроса, node пока не менялась).
          const nativeFlags = opts.lists ? getListParagraphFlags(node, oldText) : null;

          let newText = typografize(workingText, opts);

          if (opts.lists) {
            const combinedFlags = manualTypes.map((t, i) => !!t || (nativeFlags && nativeFlags[i]));
            newText = capitalizeListParagraphs(newText, combinedFlags);
            newText = stripListTrailingPeriod(newText, combinedFlags);
            // Не список: короткий самостоятельный текст без продолжения (один
            // абзац, одно предложение) — та же логика "точка в конце не нужна",
            // только область другая. Безопасно вызывать и на списочном тексте —
            // если абзац уже обработан выше, точки там просто больше нет, и
            // функция не находит, что резать (см. её ранние проверки).
            newText = stripSingleSentenceTrailingPeriod(newText);
          }

          const didChange = await applyTypography(node, newText);

          if (opts.lists && manualTypes.some(Boolean)) {
            applyListMarkers(node, newText, manualTypes);
          }

          // Подчёркивание — стилизация диапазона, не правка текста, поэтому
          // применяется после applyTypography, когда node.characters уже
          // финальный (newText). loadFontsForNode вызывается отдельно от
          // applyTypography — та грузит шрифт только если текст реально
          // менялся (early return при oldText === newText), а подчеркнуть
          // нужно и когда typografize ничего в тексте не поправил.
          let underlined = false;
          if (opts.underline) {
            await loadFontsForNode(node);
            underlined = applyUnderlines(node, newText);
          }

          if (didChange || underlined) changed++;
        } catch (_e) {
          skipped++;
          const rawMessage = (_e && _e.message) || String(_e);
          // Самая частая причина пропуска — недоступный шрифт: слой
          // использует шрифт, которого нет на компьютере (не установлен
          // локально или не подключён из библиотеки Figma). Без загруженного
          // шрифта Figma не даёт менять characters — это ограничение самого
          // API, плагин его обойти не может. Сообщение Figma техническое
          // ("The font ... could not be loaded"), добавляем понятный русский
          // хвост с тем, что реально делать: установить шрифт или временно
          // подменить его на слое.
          const reason = /font .* could not be loaded/i.test(rawMessage)
            ? rawMessage + ' — установите шрифт локально или временно замените его на этом слое и запустите плагин ещё раз'
            : rawMessage;
          skippedDetails.push({ name: node.name, reason });
        } finally {
          // В finally, а не после try: ветка со слишком длинным слоем выходит
          // через continue и иначе пропустила бы и счётчик, и передышку.
          processed++;
          if (processed % YIELD_EVERY === 0) {
            figma.ui.postMessage({ type: 'progress', done: processed, total: nodes.length, changed });
            await yieldToEventLoop();
          }
        }
      }
    } catch (e) {
      fatal = e;
    } finally {
      running = false;
    }

    if (fatal) {
      figma.ui.postMessage({ type: 'result', ok: false, error: 'Сбой при обработке. Изменено до сбоя: ' + changed });
      figma.notify('Типограф: сбой при обработке');
      return;
    }

    // Список пропущенных уходит в сам UI (не в консоль — обычным
    // пользователем консоль плагина неудобно пользоваться), раскрывается по
    // клику на "пропущено N" в статусе.
    figma.ui.postMessage({ type: 'result', ok: true, total: nodes.length, changed, skipped, processed, stopped, skippedDetails });
    // Тост на холсте дублирует итог: окно плагина маленькое и часто перекрыто
    // тем самым фреймом, который правили, — статус в подвале UI видно не всегда.
    if (stopped) {
      figma.notify(`Типограф: остановлено, изменено ${changed} из ${processed}`);
    } else {
      figma.notify(changed
        ? `Типограф: изменено ${changed} из ${nodes.length}`
        : 'Типограф: всё уже по типографике');
    }
  }

  if (msg.type === 'cancel') {
    figma.closePlugin();
  }
};
