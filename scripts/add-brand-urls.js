let totalAdded = 0;
let totalSkipped = 0;
const files = fs.readdirSync(CATS_DIR).filter(f => f.endsWith('.json')).sort();

for (const file of files) {
  const filePath = path.join(CATS_DIR, file);
  const raw = fs.readFileSync(filePath, 'utf8');
  const data = JSON.parse(raw);

  if (!data || !Array.isArray(data.items)) continue;

  let fileModified = false;
  for (const item of data.items) {
    if (!item || typeof item !== 'object') continue;
    if ('brandUrl' in item) continue;

    const figma = item.figma;
    if (!figma || !BRAND_URLS[figma]) {
      totalSkipped++;
      continue;
    }

    item.brandUrl = BRAND_URLS[figma];
    totalAdded++;
    fileModified = true;
  }

  if (fileModified && !DRY_RUN) {
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
    console.log(`✓ ${file}`);
  } else if (fileModified) {
    console.log(`[dry-run] ${file}: would add brandUrl to items`);
  }
}

