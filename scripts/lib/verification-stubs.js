// Сервисы, кладущие префикс в имя файла: yandex_<hex>, google<hex>, zen_<...>.
const PREFIXED = /^(yandex_|bing|google|zen_)/i;

// Яндекс Дистрибуция выдаёт файл без префикса — в имени только код. Такие
// перечисляем поимённо: шаблон «любой буквенно-цифровой код» рано или поздно
// проглотил бы обычную страницу и снял бы с неё все SEO-проверки молча.
const BARE = new Set([
  '842qvr829rssskke.html', // Яндекс Дистрибуция
]);

/** @param {string} name — имя файла в корне сайта (без директорий). */
const isVerificationStub = (name) => PREFIXED.test(name) || BARE.has(name);

